// Per-user integration required by modern GlobalShortcuts portals for host apps.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
if (process.platform !== 'linux' || process.argv.length !== 3) {
  throw new Error('Usage on Linux: node scripts/install-desktop-entry.cjs /absolute/path/to/client.AppImage');
}
const executable = fs.realpathSync(process.argv[2]);
if (!fs.statSync(executable).isFile()) throw new Error('AppImage must be a file.');
if (/[\r\n]/.test(executable)) throw new Error('Newlines in the executable path are unsupported.');
if (executable.includes('=')) throw new Error('Desktop entries do not support an equals sign in the executable path. Move the AppImage to another path.');
// Exec argument quoting is decoded after the desktop entry's string escaping.
// https://specifications.freedesktop.org/desktop-entry/latest/exec-variables.html
const argument = executable.replace(/[\\"`$]/g, '\\$&').replace(/%/g, '%%');
const quoted = '"' + argument.replace(/\\/g, '\\\\') + '"';
// GIO checks the executable before expanding %%; env receives the expanded path.
const command = executable.includes('%') ? '/usr/bin/env ' + quoted : quoted;
const folder = path.join(process.env.XDG_DATA_HOME || path.join(os.homedir(), '.local/share'), 'applications');
const destination = path.join(folder, 'dev.local.deepl-client.desktop');
const marker = '# Generated by DeepL Client desktop integration\n';
if (fs.existsSync(destination) && !fs.readFileSync(destination, 'utf8').startsWith(marker)) {
  throw new Error('Existing custom desktop entry preserved: ' + destination);
}
fs.mkdirSync(folder, {recursive: true});
fs.writeFileSync(destination, marker + `[Desktop Entry]\nType=Application\nVersion=1.0\nName=DeepL Client\nComment=Translate and improve text\nExec=${command}\nIcon=accessories-dictionary\nTerminal=false\nCategories=Office;\n`, {mode: 0o644});
console.log('Installed desktop entry: ' + destination);
